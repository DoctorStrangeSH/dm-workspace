import { NextResponse } from 'next/server'
import { createClient } from '@/lib/supabase/server'
import { getCampaignAccess } from '@/lib/queries/access'

const STORAGE_PREFIX = '/storage/v1/object/public/handouts/'

function getStoragePath(imageUrl: string, campaignId: string): string | null {
  let path = imageUrl

  if (/^https?:\/\//i.test(imageUrl)) {
    try {
      const parsed = new URL(imageUrl)
      const configured = process.env.NEXT_PUBLIC_SUPABASE_URL
      if (!configured || parsed.origin !== new URL(configured).origin) return null
      if (!parsed.pathname.startsWith(STORAGE_PREFIX)) return null
      path = decodeURIComponent(parsed.pathname.slice(STORAGE_PREFIX.length))
    } catch {
      return null
    }
  }

  // Only allow the UUID-named files generated by createHandout, in this campaign.
  const escapedCampaignId = campaignId.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const pattern = new RegExp(`^${escapedCampaignId}/[a-f0-9-]{36}\\.(png|jpg|webp|gif|avif)$`, 'i')
  return pattern.test(path) ? path : null
}

export async function GET(
  _request: Request,
  context: { params: Promise<{ id: string }> }
) {
  const { id } = await context.params
  const supabase = await createClient()

  const { data: handout, error } = await supabase
    .from('handouts')
    .select('id, campaign_id, is_visible, image_url')
    .eq('id', id)
    .maybeSingle()

  if (error || !handout) {
    return NextResponse.json({ error: 'Not found' }, { status: 404 })
  }

  const { isDm, isMember } = await getCampaignAccess(handout.campaign_id)
  if (!isMember || (!isDm && !handout.is_visible)) {
    return NextResponse.json({ error: 'Not found' }, { status: 404 })
  }

  const path = getStoragePath(handout.image_url, handout.campaign_id)
  if (!path) return NextResponse.json({ error: 'Not found' }, { status: 404 })

  const { data, error: signError } = await supabase.storage
    .from('handouts')
    .createSignedUrl(path, 60)

  if (signError || !data?.signedUrl) {
    return NextResponse.json({ error: 'Image unavailable' }, { status: 404 })
  }

  return NextResponse.redirect(data.signedUrl, {
    status: 302,
    headers: {
      'Cache-Control': 'private, no-store, max-age=0',
      'Referrer-Policy': 'no-referrer',
      'X-Content-Type-Options': 'nosniff',
    },
  })
}
