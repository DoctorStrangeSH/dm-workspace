export interface WildMagicResult {
  roll: number
  effect: WildMagicEffect
}

export function generateWildMagic(): WildMagicResult {
  const roll = Math.floor(Math.random() * 100) + 1
  const effect = WILD_MAGIC_TABLE.find((e) => e.roll === roll) ?? WILD_MAGIC_TABLE[0]
  return { roll, effect }
}
