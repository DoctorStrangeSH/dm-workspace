const FULL_CASTERS = ['bard', 'cleric', 'druid', 'sorcerer', 'wizard']
const HALF_CASTERS = ['paladin', 'ranger']
// warlock — особый (pact magic), пропускаем для MVP

/**
 * Возвращает spell slots для класса и уровня.
 * Возвращает пустой объект для не-кастеров.
 */
export function getSpellSlotsForLevel(
  classSlug: string,
  level: number
): SpellSlots {
  const clampedLevel = Math.max(1, Math.min(20, level))

  let table: SlotTable | null = null

  if (FULL_CASTERS.includes(classSlug)) {
    table = FULL_CASTER_SLOTS
  } else if (HALF_CASTERS.includes(classSlug)) {
    table = HALF_CASTER_SLOTS
  }

  if (!table) return {}

  const slots = table[clampedLevel] ?? {}
  const result: SpellSlots = {}

  for (const [lvl, count] of Object.entries(slots)) {
    result[Number(lvl)] = { current: count, max: count }
  }

  return result
}